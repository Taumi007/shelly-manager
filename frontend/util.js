export function num(hass, entityId) {
  const st = entityId && hass?.states[entityId];
  if (!st) return null;
  const v = parseFloat(st.state);
  return Number.isFinite(v) ? v : null;
}

export function fmtW(v) {
  if (v === null || v === undefined || Number.isNaN(v)) return "–";
  const a = Math.abs(v);
  if (a >= 10000) return `${(v / 1000).toFixed(1)} kW`;
  if (a < 10 && a !== 0) return `${v.toFixed(1)} W`;
  return `${Math.round(v)} W`;
}

export function fmtDuration(s) {
  if (s === null || s === undefined) return "–";
  const d = Math.floor(s / 86400), hh = Math.floor((s % 86400) / 3600), m = Math.floor((s % 3600) / 60);
  if (d) return `${d} d ${hh} h`;
  if (hh) return `${hh} h ${m} min`;
  return `${m} min`;
}

export function fmtAgo(ts) {
  if (!ts) return "–";
  return fmtDuration(Math.max(0, Date.now() / 1000 - ts)) + " her";
}

export function storage(key, fallback) {
  try {
    const v = localStorage.getItem(key);
    return v ? JSON.parse(v) : fallback;
  } catch {
    return fallback;
  }
}

