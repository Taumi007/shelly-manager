export const WIFI_CODES = new Set(["rssi", "rssi_jitter"]);

// Symbol für die Problemspalte/Statusspalte: WLAN-Symbol, wenn ausschließlich WLAN-Probleme vorliegen
export function problemIcon(row, size = 15) {
  const sev = SEVERITY[row.severity] ?? SEVERITY.info;
  const wifiOnly = row.problems.length && row.problems.every((p) => WIFI_CODES.has(p.code));
  return h("span", { class: `${sev.cls}${wifiOnly ? " wifiprob" : ""}`, title: (wifiOnly ? "Nur WLAN:\n" : "") + row.problems.map((p) => `• ${p.text}`).join("\n") },
    icon(wifiOnly ? MDI.wifi : sev.icon, size));
}

export function debounce(fn, ms) {
  let t;
  return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
}

